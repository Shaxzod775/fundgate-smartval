export const getArticleIcon = (iconType: string, size?: number, color?: string) => {
  const props = { size, color };
  switch (iconType) {
    case 'guide':
      return <GuideIcon {...props} />;
    case 'robot':
    case 'ai':
      return <RobotIcon {...props} />;
    case 'link':
    case 'integration':
      return <LinkIcon {...props} />;
    case 'checklist':
    case 'criteria':
      return <ChecklistIcon {...props} />;
    case 'target':
    case 'team':
      return <TargetIcon {...props} />;
    case 'lightbulb':
    case 'product':
      return <LightbulbIcon {...props} />;
    case 'trending':
    case 'market':
      return <TrendingUpIcon {...props} />;
    case 'finance':
    case 'money':
      return <FinanceIcon {...props} />;
    case 'rocket':
    case 'traction':
      return <RocketIcon {...props} />;
    default:
      return <GuideIcon {...props} />;
  }
};

